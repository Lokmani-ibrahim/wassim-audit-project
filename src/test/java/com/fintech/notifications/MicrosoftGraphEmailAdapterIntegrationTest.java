package com.fintech.notifications;

import com.fintech.notifications.adapter.graph.MicrosoftGraphEmailAdapter;
import com.fintech.notifications.port.EmailNotificationPort;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.core.env.Environment;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatCode;

@SpringBootTest(
        properties = {
                "neos.notifications.microsoft-graph.enabled=true"
        }
)
class MicrosoftGraphEmailAdapterIntegrationTest {

    @Autowired
    private EmailNotificationPort emailNotificationPort;

    @Autowired
    private Environment environment;

    @Test
    void sendsRealEmailThroughMicrosoftGraph() {

        String runGraphIt =
                environment.getProperty(
                        "RUN_GRAPH_IT"
                );

        System.out.println(
                "RUN_GRAPH_IT loaded by Spring = "
                        + runGraphIt
        );

        Assumptions.assumeTrue(
                Boolean.parseBoolean(runGraphIt),
                "RUN_GRAPH_IT must be true"
        );

        String recipient =
                environment.getProperty(
                        "GRAPH_TEST_RECIPIENT"
                );

        assertThat(recipient)
                .as(
                        "GRAPH_TEST_RECIPIENT must be configured"
                )
                .isNotBlank();

        assertThat(
                emailNotificationPort
        ).isInstanceOf(
                MicrosoftGraphEmailAdapter.class
        );

        assertThatCode(
                () ->
                        emailNotificationPort.sendHtml(
                                recipient,
                                "Neos notification integration test",
                                """
                                <html>
                                  <body>
                                    <h2>Neos</h2>
                                    <p>
                                      Microsoft Graph email integration
                                      is working correctly.
                                    </p>
                                    <p>
                                      This message was generated by the
                                      C4 notification integration test.
                                    </p>
                                  </body>
                                </html>
                                """
                        )
        ).doesNotThrowAnyException();
    }
}