-- ============================================================
-- NEOS
-- Flyway Migration V1
-- Identity and Onboarding Schema
--
-- PostgreSQL stores application state.
-- Authentication credentials are owned by Keycloak.
-- KYC documents are owned by the KYC provider.
-- Financial balances and ledger entries are owned by Formance.
-- ============================================================


-- ============================================================
-- USERS
-- ============================================================

CREATE TABLE users (
                       id UUID PRIMARY KEY,

    -- Stable OpenID Connect "sub" issued by Keycloak.
    -- This is NOT an access token.
                       keycloak_subject VARCHAR(255) NOT NULL UNIQUE,

                       email VARCHAR(320) NOT NULL UNIQUE,

                       phone_number VARCHAR(32),

                       account_type VARCHAR(32) NOT NULL DEFAULT 'PERSONAL',

                       account_status VARCHAR(32) NOT NULL DEFAULT 'PENDING_KYC',

                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT chk_users_account_type
                           CHECK (
                               account_type IN (
                                                'PERSONAL',
                                                'BUSINESS'
                                   )
                               ),

                       CONSTRAINT chk_users_account_status
                           CHECK (
                               account_status IN (
                                                  'PENDING_KYC',
                                                  'ACTIVE',
                                                  'SUSPENDED',
                                                  'CLOSED'
                                   )
                               )
);


-- ============================================================
-- KYC STATUS
-- ============================================================

CREATE TABLE kyc_status (
                            id UUID PRIMARY KEY,

                            user_id UUID NOT NULL,

                            provider VARCHAR(50) NOT NULL DEFAULT 'SUMSUB',

    -- External applicant identifier assigned by Sumsub.
    -- NULL until the KYC process is started.
                            provider_applicant_id VARCHAR(255),

                            status VARCHAR(32) NOT NULL DEFAULT 'NOT_STARTED',

                            started_at TIMESTAMPTZ,

                            decided_at TIMESTAMPTZ,

                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT fk_kyc_status_user
                                FOREIGN KEY (user_id)
                                    REFERENCES users(id),

    -- Validation 1 maintains one current KYC state per user.
                            CONSTRAINT uq_kyc_status_user
                                UNIQUE (user_id),

    -- The same provider applicant must not be linked twice.
                            CONSTRAINT uq_kyc_provider_applicant
                                UNIQUE (provider, provider_applicant_id),

                            CONSTRAINT chk_kyc_status
                                CHECK (
                                    status IN (
                                               'NOT_STARTED',
                                               'PENDING',
                                               'IN_REVIEW',
                                               'APPROVED',
                                               'REJECTED'
                                        )
                                    )
);


-- ============================================================
-- DEVICES
-- ============================================================

CREATE TABLE devices (
                         id UUID PRIMARY KEY,

                         user_id UUID NOT NULL,

    -- Identifier generated by the Neos application installation.
    -- Do not use a mutable hardware identifier.
                         installation_id VARCHAR(255) NOT NULL,

                         platform VARCHAR(20) NOT NULL,

                         trusted BOOLEAN NOT NULL DEFAULT FALSE,

                         first_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         revoked_at TIMESTAMPTZ,

                         CONSTRAINT fk_devices_user
                             FOREIGN KEY (user_id)
                                 REFERENCES users(id),

                         CONSTRAINT uq_devices_user_installation
                             UNIQUE (user_id, installation_id),

                         CONSTRAINT chk_devices_platform
                             CHECK (
                                 platform IN (
                                              'ANDROID',
                                              'IOS',
                                              'WEB'
                                     )
                                 )
);


-- ============================================================
-- INDEXES
-- ============================================================

-- Useful for the compliance/backoffice KYC queue:
-- "Show me all users currently IN_REVIEW."
CREATE INDEX idx_kyc_status_status
    ON kyc_status(status);

-- Useful when retrieving all devices belonging to a user.
CREATE INDEX idx_devices_user_id
    ON devices(user_id);

-- Useful later for security/device inactivity queries.
CREATE INDEX idx_devices_last_seen_at
    ON devices(last_seen_at);