const { chromium } = require('playwright-core');
const fs = require('fs');
const out = process.argv[2];
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true });
  const ctx = await browser.newContext({ viewport: { width: 1360, height: 860 } });
  const page = await ctx.newPage();
  const log = [];
  const shot = async (name) => { await page.waitForTimeout(700); await page.screenshot({ path: `${out}/${name}.png` }); log.push(`${name} ${page.url()}`); };
  await page.goto('http://127.0.0.1:5174/demo.html', { waitUntil: 'networkidle' });
  await shot('d01-login');
  await page.fill('input[type=text]', 'officer@example.com'); await page.fill('input[type=password]', 'x');
  await page.locator('button[type=submit]').click(); await page.waitForTimeout(1000);
  await shot('d02-overview');
  const nav = async (label) => { await page.locator('nav a', { hasText: label }).first().click(); await page.waitForTimeout(800); };
  await nav('Users'); await shot('d03-users');
  await page.locator('tbody tr').first().click(); await shot('d04-user-detail');
  await page.locator('button', { hasText: /Suspend/ }).first().click().catch(() => {}); await shot('d05-user-suspend-dialog');
  await page.locator('button', { hasText: 'Cancel' }).first().click().catch(() => {});
  await nav('KYC reviews'); await shot('d06-kyc-queue');
  await page.locator('tbody tr').first().click(); await shot('d07-kyc-case');
  await nav('Transactions'); await shot('d08-transactions');
  await page.locator('tbody tr').first().click(); await shot('d09-transaction-detail');
  await page.keyboard.press('Escape'); await page.locator('.drawer-close').click().catch(() => {});
  await nav('Reconciliation'); await shot('d10-reconciliation');
  await nav('Alerts'); await shot('d11-alerts');
  fs.writeFileSync(`${out}/demo-shots.log`, log.join('\n'));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
